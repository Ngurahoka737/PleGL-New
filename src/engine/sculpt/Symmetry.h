#pragma once

#include <array>
#include <cstdint>

#include "core/Types.h"

namespace plegl {

// Brush symmetry: mirrors across the object's local coordinate planes, plus a radial repeat
// around one local axis. All copies of a dab are the images of the dab under a finite group of
// linear maps about the local origin (the same reference the X mirror always used).

enum class Axis : std::uint8_t { X = 0, Y = 1, Z = 2 };

inline constexpr int kMaxRadialCount = 32;
inline constexpr int kMaxSymmetryCopies = 64;
inline constexpr int kManySymmetryCopies = 16;     // The panel warns above this many copies.
inline constexpr int kMaxDyntopoCopies = 24;       // Dynamic topology runs only up to this many.
inline constexpr float kCopyMergeFraction = 0.05f; // Merge distance, as a fraction of the radius.
inline constexpr float kPinTolerance = 1e-5f;      // Of the object's bounds diagonal.
inline constexpr float kShareExponent = 1.0f;      // Overlapping copies split a vertex by f^p.

struct SymmetrySpec {
  bool x = false, y = false, z = false;  // Mirror across local x = 0 / y = 0 / z = 0.
  Axis radialAxis = Axis::Y;
  int radialCount = 1;                   // 1 = off, else 2..32 copies around the axis.
  bool operator==(const SymmetrySpec&) const = default;
};

// Number of distinct copies (the group's order).
int copyCount(const SymmetrySpec& spec);
// Largest radial count (at least 1) that keeps copyCount at or under kMaxSymmetryCopies.
int maxRadialCount(const SymmetrySpec& spec);
// The spec with radialCount clamped to [1, maxRadialCount] and a valid axis.
SymmetrySpec sanitized(SymmetrySpec spec);

using OpMask = std::uint64_t;  // A set of ops by index.

struct SymmetryOp {
  Mat3 L{1.0f};
  float det = 1.0f;
};

// Applies a linear map, skipping zero entries, so maps made of 0 and +-1 (every mirror and every
// quarter turn) move points without any rounding and keep the sign of each coordinate.
Vec3 transform(const Mat3& L, const Vec3& p);

// The group of maps L = R_j * D: D flips the coordinates whose mirror is on, R_j turns by
// 2 pi j / N around the radial axis. Ops are ordered with D outermost (I, Sx, Sy, Sz, SxSy, SxSz,
// SySz, SxSySz) and j inner; op 0 is the identity. Duplicates (an even N with two perpendicular
// mirrors) are dropped, keeping the first.
class SymmetryGroup {
 public:
  SymmetryGroup();                              // Identity only.
  explicit SymmetryGroup(const SymmetrySpec& spec);  // The spec must be sanitized.

  const SymmetrySpec& spec() const { return spec_; }
  int size() const { return size_; }
  const SymmetryOp& op(int k) const { return ops_[static_cast<std::size_t>(k)]; }
  int mul(int a, int b) const { return mul_[static_cast<std::size_t>(a)][static_cast<std::size_t>(b)]; }
  int inverse(int a) const { return inv_[static_cast<std::size_t>(a)]; }
  OpMask all() const { return size_ >= 64 ? ~OpMask{0} : (OpMask{1} << size_) - 1; }
  // The subgroup generated by `generators` (always contains op 0).
  OpMask closure(OpMask generators) const;
  // Mean of L over a subgroup: the projector onto the points it fixes.
  Mat3 projector(OpMask h) const;
  // Mean of det * L over a subgroup: projects rotation vectors (axial vectors).
  Mat3 axialProjector(OpMask h) const;
  // Projector onto the points op k fixes.
  const Mat3& fixProjector(int k) const { return fix_[static_cast<std::size_t>(k)]; }
  // The subgroup generated by every op that moves p by at most 2 eps.
  OpMask stabilizer(const Vec3& p, float eps) const;
  // Coordinate planes that are mirror planes of the group (bit a: the plane p_a = 0), and
  // coordinate axes that some rotation of the group turns about (bit a: axis a).
  std::uint8_t mirrorPlanes() const { return planes_; }
  std::uint8_t rotationAxes() const { return axes_; }

 private:
  SymmetrySpec spec_;
  int size_ = 1;
  std::array<SymmetryOp, kMaxSymmetryCopies> ops_{};
  std::array<std::array<std::uint8_t, kMaxSymmetryCopies>, kMaxSymmetryCopies> mul_{};
  std::array<std::uint8_t, kMaxSymmetryCopies> inv_{};
  std::array<Mat3, kMaxSymmetryCopies> fix_{};
  std::uint8_t planes_ = 0, axes_ = 0;
};

// Copies whose centres nearly coincide act as one dab: a cluster is a coset kH of the subgroup H
// generated by the ops that move the centre less than the merge distance, or whose plane or axis
// lies closer to it than that. Its dab sits at the mean
// of its members' centres, and vectors carried from the primary dab are averaged the same way.
struct CopyCluster {
  int op = 0;            // Lowest op of the coset: the frame the cluster lives in.
  OpMask members = 1;    // The coset.
  OpMask subgroup = 1;   // H.
  Vec3 center{0.0f};     // L_op * P_H * c.
  Mat3 polar{1.0f};      // L_op * P_H: a primary-frame vector (normal, offset) to this cluster.
  Mat3 axial{1.0f};      // det_op * L_op * Q_H: a primary-frame rotation vector to this cluster.
  Mat3 localProjector{1.0f};  // L_op * P_H * L_op^T: onto what the cluster's members agree on.
  bool merged() const { return subgroup != 1; }
  // Projects a vector measured at this cluster onto the directions its merged copies agree on.
  Vec3 projectLocal(const Vec3& v) const;
};

using CopyClusters = std::array<CopyCluster, kMaxSymmetryCopies>;

// Clusters of the copies of a dab at c, in order of their lowest op (cluster 0 holds op 0).
int clusterCopies(const SymmetryGroup& group, const Vec3& c, float mergeDist, CopyClusters& out);
// Clusters for a given subgroup H (the cosets of H).
int clustersOf(const SymmetryGroup& group, OpMask subgroup, const Vec3& c, CopyClusters& out);

// A vertex held on the symmetry planes or axes it started on (within the pin tolerance).
struct SeamPin {
  Mat3 P{1.0f};              // Projector onto the points its stabiliser fixes.
  std::uint8_t zeroAxes = 0; // Coordinates that are exactly 0 on that subspace.
};
SeamPin seamPin(const SymmetryGroup& group, const Vec3& p, float eps);
// The pinned position for a vertex that started at `start` and was moved to `p`: only the part of
// the move along the subspace is kept, the result is snapped onto it, and zero coordinates are +0.
Vec3 snapPinned(const SeamPin& pin, const Vec3& start, const Vec3& p);

// Coordinates of p forced to 0 by the group (bits as in mirrorPlanes): a mirror plane p lies on,
// or both perpendicular coordinates of a rotation axis p lies on.
std::uint8_t pinnedAxes(std::uint8_t planes, std::uint8_t axes, const Vec3& p, float eps);

}  // namespace plegl
